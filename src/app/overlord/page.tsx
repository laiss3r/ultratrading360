'use client';

import { useMemo, useState } from 'react';
import { Info, Pause, Play, Radar, RefreshCw, Square, Target, Zap } from 'lucide-react';
import { Badge, Banner, Button, Card, Empty, Field, Stat, Toggle } from '@/components/ui';
import { DigitStrip, TickChart } from '@/components/charts';
import { useApp } from '@/state/store';
import { createStrategy, validateStrategy, type Strategy } from '@/lib/engine/strategies';
import type { ContractType } from '@/lib/deriv/contracts';
import { MODE_LABEL, money, pct, signed } from '@/lib/format';

const QUICK_CONTRACTS: { value: ContractType; label: string; needsBarrier: boolean; note: string }[] = [
  { value: 'DIGITODD', label: 'Digit Odd', needsBarrier: false, note: 'Wins if the final digit is 1,3,5,7,9 — 5 of 10 outcomes.' },
  { value: 'DIGITEVEN', label: 'Digit Even', needsBarrier: false, note: 'Wins if the final digit is 0,2,4,6,8 — 5 of 10 outcomes.' },
  { value: 'DIGITOVER', label: 'Digit Over', needsBarrier: true, note: 'Wins if the final digit is strictly ABOVE the barrier.' },
  { value: 'DIGITUNDER', label: 'Digit Under', needsBarrier: true, note: 'Wins if the final digit is strictly BELOW the barrier.' },
  { value: 'DIGITMATCH', label: 'Digit Matches', needsBarrier: true, note: 'Wins only if the final digit equals the barrier — 1 of 10.' },
  { value: 'DIGITDIFF', label: 'Digit Differs', needsBarrier: true, note: 'Wins unless the final digit equals the barrier — 9 of 10.' },
];

interface QuickConfig {
  contractType: ContractType;
  barrier: number;
  market: string;
  stake: number;
  duration: number;
  durationUnit: Strategy['durationUnit'];
  cooldown: number;
  targetProfit: number;
  stopLoss: number;
  maxTrades: number;
  recovery: boolean;
  multiplier: number;
  stepLimit: number;
}

/**
 * Theoretical win probability for a digit contract, assuming a FAIR uniform draw.
 * This is the honest baseline to compare a broker payout against — not a prediction.
 */
function fairWinProbability(ct: ContractType, barrier: number): number {
  switch (ct) {
    case 'DIGITODD':
    case 'DIGITEVEN':
      return 0.5;
    case 'DIGITOVER':
      return Math.max(0, 9 - barrier) / 10; // digits barrier+1 .. 9
    case 'DIGITUNDER':
      return Math.max(0, barrier) / 10; // digits 0 .. barrier-1
    case 'DIGITMATCH':
      return 0.1;
    case 'DIGITDIFF':
      return 0.9;
    default:
      return 0.5;
  }
}

export default function OverlordPage() {
  const s = useApp();
  const [cfg, setCfg] = useState<QuickConfig>({
    contractType: 'DIGITODD',
    barrier: 5,
    market: s.activeSymbol || 'R_100',
    stake: 0.35,
    duration: 1,
    durationUnit: 't',
    cooldown: 2,
    targetProfit: 25,
    stopLoss: 20,
    maxTrades: 50,
    recovery: false,
    multiplier: 1.5,
    stepLimit: 3,
  });
  const [launchMsg, setLaunchMsg] = useState<{ ok: boolean; text: string } | null>(null);
  const [showMethod, setShowMethod] = useState(true);
  const set = (p: Partial<QuickConfig>) => setCfg((c) => ({ ...c, ...p }));

  const meta = QUICK_CONTRACTS.find((c) => c.value === cfg.contractType)!;
  const pWin = fairWinProbability(cfg.contractType, cfg.barrier);

  // What the strategy will actually look like — validated BEFORE launch, not after.
  const preview = useMemo<Strategy>(() => {
    return createStrategy({
      name: `Overlord · ${cfg.contractType} ${cfg.market}`,
      market: cfg.market,
      contractType: cfg.contractType,
      barrier: meta.needsBarrier ? cfg.barrier : undefined,
      duration: cfg.duration,
      durationUnit: cfg.durationUnit,
      stake: cfg.stake,
      currency: s.session?.currency ?? 'USD',
      entry: { id: 'root', op: 'AND', children: [{ id: 'always', kind: 'always' }] },
      cooldownSeconds: cfg.cooldown,
      maxTrades: cfg.maxTrades,
      maxExposure: cfg.stake * Math.max(1, cfg.maxTrades),
      notes: 'Generated by Overlord Pro quick-launch. Unconditional entry; the risk manager governs everything else.',
    });
  }, [cfg, meta.needsBarrier, s.session?.currency]);

  const previewValidation = useMemo(() => validateStrategy(preview), [preview]);

  // Effective limits this launch would apply, taking the global caps into account.
  const effective = useMemo(() => {
    const L = s.settings.limits;
    return {
      maxStake: Math.min(L.maxStake, cfg.recovery ? Math.max(cfg.stake, L.maxStake) : cfg.stake),
      stakeCap: L.maxStake,
      stopLoss: Math.min(cfg.stopLoss, L.maxSessionLoss > 0 ? L.maxSessionLoss : cfg.stopLoss),
      targetProfit: cfg.targetProfit,
      maxTrades: Math.min(cfg.maxTrades, L.maxTrades),
      sessionExposure: L.maxSessionExposure,
    };
  }, [cfg, s.settings.limits]);

  // Worst-case recovery ladder, clamped the same way the risk manager clamps it.
  const ladder = useMemo(() => {
    if (!cfg.recovery) return [];
    const out: number[] = [];
    let st = cfg.stake;
    for (let i = 0; i <= cfg.stepLimit; i++) {
      out.push(Number(Math.min(st, s.settings.limits.maxStake).toFixed(2)));
      st *= cfg.multiplier;
    }
    return out;
  }, [cfg, s.settings.limits.maxStake]);

  async function launch() {
    setLaunchMsg(null);
    if (!previewValidation.valid) {
      setLaunchMsg({ ok: false, text: previewValidation.errors.join(' · ') });
      return;
    }
    // Apply this launch's session targets to the enforced limits BEFORE starting, so the risk
    // manager is what stops the bot — not a UI poll that could be bypassed.
    await s.setSettings({
      limits: {
        ...s.settings.limits,
        maxSessionLoss: effective.stopLoss,
        maxSessionProfit: effective.targetProfit,
        maxTrades: effective.maxTrades,
      },
      recovery: {
        ...s.settings.recovery,
        enabled: cfg.recovery,
        multiplier: cfg.multiplier,
        stepLimit: cfg.stepLimit,
        maxStake: s.settings.limits.maxStake,
      },
    });
    s.risk.resetSession();
    const saved = await s.saveStrategy(preview);
    if (!saved.ok) {
      setLaunchMsg({ ok: false, text: saved.message });
      return;
    }
    if (cfg.market !== s.activeSymbol) await s.selectSymbol(cfg.market);
    const r = await s.runStrategy(preview.id);
    setLaunchMsg({ ok: r.ok, text: r.message });
  }

  const running = s.botState === 'running' || s.botState === 'paused' || s.botState === 'starting';

  return (
    <div className="mx-auto max-w-[1600px] space-y-3 p-4">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <div>
          <h2 className="flex items-center gap-2 text-sm font-bold text-prominent">
            <Zap className="h-4 w-4 text-coral" /> Overlord Pro · quick launch
          </h2>
          <p className="text-xxs text-less-prominent">
            Configure a contract in seconds. Session targets and caps are written into the enforced risk limits before launch, so the bot is
            stopped by the risk manager and not by a UI timer.
          </p>
        </div>
        <Badge tone={s.settings.mode === 'deriv_real' ? 'loss' : 'info'}>
          {MODE_LABEL[s.settings.mode]}
        </Badge>
      </div>

      {launchMsg && <Banner tone={launchMsg.ok ? 'success' : 'danger'}>{launchMsg.text}</Banner>}

      <div className="grid grid-cols-1 gap-3 xl:grid-cols-[minmax(0,1fr)_380px]">
        <div className="min-w-0 space-y-3">
          {/* --------------------------------------------- contract config */}
          <Card title="Contract" subtitle="What will be bought, on which market, for how long.">
            <div className="grid grid-cols-2 gap-2.5 md:grid-cols-3">
              <Field label="Contract type" className="col-span-2 md:col-span-3">
                <div className="grid grid-cols-2 gap-1.5 md:grid-cols-3">
                  {QUICK_CONTRACTS.map((c) => (
                    <button
                      key={c.value}
                      type="button"
                      onClick={() => set({ contractType: c.value })}
                      className={`rounded border px-2.5 py-2 text-left transition-colors ${
                        cfg.contractType === c.value ? 'border-brand/50 bg-coral/10' : 'border-line bg-section-1 hover:border-line'
                      }`}
                    >
                      <div className={`text-xs font-bold ${cfg.contractType === c.value ? 'text-coral' : 'text-prominent'}`}>{c.label}</div>
                      <div className="num mt-0.5 text-xxs text-less-prominent">{c.value}</div>
                    </button>
                  ))}
                </div>
              </Field>

              <Field label="Market" hint={s.symbols.length ? `${s.symbols.length} live markets discovered` : 'connect for full discovery'}>
                <select value={cfg.market} onChange={(e) => set({ market: e.target.value })}>
                  {[...new Set([cfg.market, s.activeSymbol, ...s.symbols.map((x) => x.underlying_symbol)])].map((m) => {
                    const sym = s.symbols.find((x) => x.underlying_symbol === m);
                    return <option key={m} value={m}>{sym ? `${sym.underlying_symbol_name} (${m})` : m}</option>;
                  })}
                </select>
              </Field>

              {meta.needsBarrier && (
                <Field label="Barrier digit" hint="Strict inequality for over/under.">
                  <input type="number" min={0} max={9} step={1} value={cfg.barrier} onChange={(e) => set({ barrier: Number(e.target.value) })} className="num" />
                </Field>
              )}

              <Field label="Stake" hint={`capped at ${money(effective.stakeCap, '')}`}>
                <input type="number" min={0.35} step={0.05} value={cfg.stake} onChange={(e) => set({ stake: Number(e.target.value) })} className="num" />
              </Field>

              <Field label="Duration">
                <div className="flex gap-1.5">
                  <input type="number" min={1} step={1} value={cfg.duration} onChange={(e) => set({ duration: Number(e.target.value) })} className="num" />
                  <select value={cfg.durationUnit} onChange={(e) => set({ durationUnit: e.target.value as Strategy['durationUnit'] })} className="w-[92px]">
                    <option value="t">ticks</option>
                    <option value="s">seconds</option>
                    <option value="m">minutes</option>
                  </select>
                </div>
              </Field>

              <Field label="Cooldown (s)">
                <input type="number" min={0} step={1} value={cfg.cooldown} onChange={(e) => set({ cooldown: Number(e.target.value) })} className="num" />
              </Field>
            </div>
            <Banner tone="info" className="mt-2.5">
              {meta.note} Under a fair uniform draw the theoretical win probability is{' '}
              <strong className="num">{pct(pWin, 1)}</strong>. Whether that is profitable depends entirely on the payout Deriv quotes — check
              the live proposal before committing real stake.
            </Banner>
          </Card>

          {/* ---------------------------------------------- session limits */}
          <Card title="Session targets & caps" subtitle="Written into the enforced risk limits at launch.">
            <div className="grid grid-cols-2 gap-2.5 md:grid-cols-4">
              <Field label="Target profit" hint="Take-profit halt. 0 disables.">
                <input type="number" min={0} step={5} value={cfg.targetProfit} onChange={(e) => set({ targetProfit: Number(e.target.value) })} className="num" />
              </Field>
              <Field label="Stop loss" hint={`global cap ${money(s.settings.limits.maxSessionLoss, '')}`}>
                <input type="number" min={0} step={5} value={cfg.stopLoss} onChange={(e) => set({ stopLoss: Number(e.target.value) })} className="num" />
              </Field>
              <Field label="Max trades" hint={`global cap ${s.settings.limits.maxTrades}`}>
                <input type="number" min={1} step={10} value={cfg.maxTrades} onChange={(e) => set({ maxTrades: Number(e.target.value) })} className="num" />
              </Field>
              <Field label="Max stake" hint="global risk cap">
                <input
                  type="number"
                  min={0.35}
                  step={0.5}
                  value={s.settings.limits.maxStake}
                  onChange={(e) => void s.setSettings({ limits: { ...s.settings.limits, maxStake: Number(e.target.value) } })}
                  className="num"
                />
              </Field>
            </div>
            <div className="mt-2 grid grid-cols-2 gap-2.5 md:grid-cols-4">
              <Field label="Max drawdown (%)" hint="of session peak equity">
                <input
                  type="number" min={0} max={1} step={0.01}
                  value={s.settings.limits.maxDrawdownPct}
                  onChange={(e) => void s.setSettings({ limits: { ...s.settings.limits, maxDrawdownPct: Number(e.target.value) } })}
                  className="num"
                />
              </Field>
              <Field label="Max session exposure">
                <input
                  type="number" min={0} step={25}
                  value={s.settings.limits.maxSessionExposure}
                  onChange={(e) => void s.setSettings({ limits: { ...s.settings.limits, maxSessionExposure: Number(e.target.value) } })}
                  className="num"
                />
              </Field>
              <Field label="Max open exposure">
                <input
                  type="number" min={0} step={5}
                  value={s.settings.limits.maxOpenExposure}
                  onChange={(e) => void s.setSettings({ limits: { ...s.settings.limits, maxOpenExposure: Number(e.target.value) } })}
                  className="num"
                />
              </Field>
              <Field label="Max daily loss">
                <input
                  type="number" min={0} step={25}
                  value={s.settings.limits.maxDailyLoss}
                  onChange={(e) => void s.setSettings({ limits: { ...s.settings.limits, maxDailyLoss: Number(e.target.value) } })}
                  className="num"
                />
              </Field>
            </div>
          </Card>

          {/* ------------------------------------------- recovery (capped) */}
          <Card title="Recovery mode" subtitle="Optional, capped escalation. Disabled by default.">
            <div className="space-y-2.5">
              <Toggle
                tone="danger"
                checked={cfg.recovery}
                onChange={(v) => set({ recovery: v })}
                label="Enable capped recovery"
                hint="After a loss the suggested stake is multiplied, then re-clamped against the max stake. It can never exceed the cap."
              />
              {cfg.recovery && (
                <>
                  <div className="grid grid-cols-2 gap-2.5 md:grid-cols-4">
                    <Field label="Multiplier">
                      <input type="number" min={1} max={5} step={0.1} value={cfg.multiplier} onChange={(e) => set({ multiplier: Number(e.target.value) })} className="num" />
                    </Field>
                    <Field label="Step limit">
                      <input type="number" min={0} max={12} step={1} value={cfg.stepLimit} onChange={(e) => set({ stepLimit: Number(e.target.value) })} className="num" />
                    </Field>
                    <div className="col-span-2">
                      <Field label="Resulting stake ladder (after clamping)">
                        <div className="flex flex-wrap items-center gap-1.5">
                          {ladder.map((v, i) => (
                            <span key={i} className="num rounded border border-line bg-section-2/50 px-1.5 py-0.5 text-xxs text-general">
                              {i > 0 && <span className="text-less-prominent">→ </span>}
                              {v.toFixed(2)}
                              {v >= effective.stakeCap - 1e-9 && <span className="ml-1 text-xxs text-orange">CAP</span>}
                            </span>
                          ))}
                        </div>
                      </Field>
                    </div>
                  </div>
                  <Banner tone="danger">
                    Recovery does not create an edge. If the contract has negative expected value, escalating the stake increases the variance
                    of the outcome while making the expected loss per session <strong>larger</strong>, not smaller. The ladder above shows the
                    clamped worst case — total committed at full escalation is{' '}
                    <strong className="num">{money(ladder.reduce((a, b) => a + b, 0), '')}</strong>.
                  </Banner>
                </>
              )}
            </div>
          </Card>
        </div>

        {/* --------------------------------------------------- right column */}
        <div className="space-y-3">
          <Card
            title="Launch"
            subtitle={`Effective caps after applying global limits`}
            right={<Badge tone={running ? 'profit' : s.botState === 'halted' ? 'warn' : 'neutral'}>{s.botState.toUpperCase()}</Badge>}
          >
            <div className="space-y-2.5">
              <div className="grid grid-cols-2 gap-2 text-xxs">
                <KV label="Effective stake cap" value={money(effective.maxStake, '')} />
                <KV label="Stop loss" value={money(effective.stopLoss, '')} />
                <KV label="Target profit" value={money(effective.targetProfit, '')} />
                <KV label="Max trades" value={String(effective.maxTrades)} />
                <KV label="Theoretical win p" value={pct(pWin, 1)} />
                <KV label="Session exposure" value={money(effective.sessionExposure, '')} />
              </div>

              {!previewValidation.valid && (
                <Banner tone="danger">
                  <ul className="list-disc space-y-0.5 pl-4">{previewValidation.errors.map((e) => <li key={e}>{e}</li>)}</ul>
                </Banner>
              )}
              {previewValidation.warnings.length > 0 && (
                <Banner tone="warn">
                  <ul className="list-disc space-y-0.5 pl-4">{previewValidation.warnings.map((w) => <li key={w}>{w}</li>)}</ul>
                </Banner>
              )}

              <div className="flex gap-2">
                <Button variant="success" size="lg" className="flex-1" disabled={running || !previewValidation.valid} onClick={() => void launch()}>
                  <Play className="h-4 w-4" /> Launch
                </Button>
                {/*
                  Icon-only controls, so each carries an accessible name. Without aria-label a
                  screen reader announces nothing at all, and these three include the button that
                  halts a running bot — the one control that must never be ambiguous.
                */}
                <Button
                  variant="outline"
                  size="lg"
                  aria-label="Pause bot"
                  title="Pause — no new contracts are opened; in-flight contracts still settle"
                  disabled={s.botState !== 'running'}
                  onClick={() => s.pauseBot()}
                >
                  <Pause className="h-4 w-4" />
                </Button>
                <Button
                  variant="outline"
                  size="lg"
                  aria-label="Resume bot"
                  title="Resume"
                  disabled={s.botState !== 'paused'}
                  onClick={() => s.resumeBot()}
                >
                  <Play className="h-4 w-4" />
                </Button>
                <Button
                  variant="danger"
                  size="lg"
                  aria-label="Stop bot"
                  title="Stop — halts immediately; any in-flight contract is allowed to settle"
                  disabled={s.botState === 'idle' || s.botState === 'stopped'}
                  onClick={() => s.stopBot('stopped from Overlord')}
                >
                  <Square className="h-4 w-4" />
                </Button>
              </div>

              {!s.settings.limits.tradingEnabled && (
                <Banner tone="warn">
                  Trading is globally disabled. Launch will refuse until you enable it in{' '}
                  <button className="underline" onClick={() => void s.setSettings({ limits: { ...s.settings.limits, tradingEnabled: true } })}>
                    one click here
                  </button>{' '}
                  or in Risk settings.
                </Banner>
              )}
              {!s.session && (
                <Banner tone="warn">{MODE_LABEL[s.settings.mode]} requires a connected Deriv account. Market data still streams.</Banner>
              )}

              {s.botDetail && <div className="num rounded border border-line bg-section-1 px-2.5 py-1.5 text-xxs text-less-prominent">{s.botDetail}</div>}
            </div>
          </Card>

          <Card title="Live status" subtitle="The market Overlord is pointed at right now." pad={false}>
            <div className="h-[130px] p-2">
              <TickChart quotes={s.quotes} points={100} />
            </div>
            <div className="border-t border-line px-3 py-2">
              <DigitStrip digits={s.digits} count={20} />
            </div>
            <div className="grid grid-cols-3 gap-2 border-t border-line p-3">
              <Stat label="Session P/L" value={signed(s.riskSnapshot.sessionPnl)} tone={s.riskSnapshot.sessionPnl >= 0 ? 'profit' : 'loss'} />
              <Stat label="Trades" value={`${s.riskSnapshot.tradesThisSession}/${effective.maxTrades}`} />
              <Stat label="Recovery step" value={`${s.riskSnapshot.recoveryStep}/${cfg.stepLimit}`} tone={s.riskSnapshot.recoveryStep >= cfg.stepLimit ? 'warn' : undefined} />
            </div>
          </Card>
        </div>
      </div>

      {/* ------------------------------------------------- market discovery */}
      <Card
        title="Market discovery & ranking"
        subtitle="Ranked from ticks actually collected in this browser session."
        right={
          <span className="flex items-center gap-2">
            <Button size="sm" variant="ghost" onClick={() => setShowMethod((v) => !v)}>
              <Info className="h-3 w-3" /> {showMethod ? 'Hide' : 'Show'} methodology
            </Button>
            <Button size="sm" variant="outline" disabled={s.dataSource !== 'deriv_live'} onClick={() => void s.rankMarkets()}>
              <RefreshCw className="h-3 w-3" /> Re-rank
            </Button>
          </span>
        }
        pad={false}
      >
        {showMethod && (
          <div className="border-b border-line bg-section-1 px-4 py-3">
            <div className="mb-1.5 flex items-center gap-1.5 text-xxs font-bold text-prominent">
              <Radar className="h-3.5 w-3.5 text-blue" /> How this ranking is computed
            </div>
            <ul className="space-y-1 text-xxs leading-relaxed text-general">
              <li>
                <strong className="text-prominent">Sample.</strong> For each open market we pull the last 300 ticks and extract the final digit using
                that instrument’s own <code className="num">pip_size</code>. Markets we cannot reach are skipped rather than scored zero.
              </li>
              <li>
                <strong className="text-prominent">Digit entropy (weight 0.6).</strong> Shannon entropy of the observed last-digit distribution,
                normalised to 0–1 where 1.0 is perfectly uniform. Near 1.0 means the sample looks like a fair 1-in-10 draw.
              </li>
              <li>
                <strong className="text-prominent">Realised movement (weight 0.3).</strong> Mean absolute per-tick change expressed in pips — a
                volatility proxy, capped at 1.0 contribution so an outlier cannot dominate.
              </li>
              <li>
                <strong className="text-prominent">Cadence (weight 0.05–0.1).</strong> Whether the instrument is a 1-second index (faster tick
                arrival) or a standard volatility index.
              </li>
            </ul>
            <Banner tone="warn" className="mt-2">
              <strong className="font-bold">What this ranking is NOT.</strong> A high score means the recent sample looked uniform and
              liquid. It does <strong>not</strong> mean the next digit is predictable, and no ordering here implies future profit. Observed
              regularity in a finite sample is not evidence of predictive power — use Signal Lab for goodness-of-fit, dependence and
              out-of-sample tests before believing any edge exists.
            </Banner>
          </div>
        )}

        {s.dataSource !== 'deriv_live' ? (
          <Empty title="Discovery needs the live Deriv feed">
            Switch the mode selector to DEMO or REAL. Public market data requires no credentials — you do not need to connect an account to
            browse and rank markets.
          </Empty>
        ) : s.rankings.length === 0 ? (
          <Empty title="No markets ranked yet">
            Press <strong>Re-rank</strong> to sample open synthetic markets. This pulls ~300 ticks per market, so it takes a few seconds.
          </Empty>
        ) : (
          <div className="max-h-[420px] overflow-auto">
            <table className="w-full text-left text-xxs">
              <thead className="sticky top-0 z-10 bg-section-1 text-xxs tracking-wider text-less-prominent uppercase">
                <tr>
                  <th className="px-3 py-2">#</th>
                  <th className="px-3 py-2">Market</th>
                  <th className="px-3 py-2 text-right">Sample</th>
                  <th className="px-3 py-2 text-right">Digit entropy</th>
                  <th className="px-3 py-2 text-right">Move (pips)</th>
                  <th className="px-3 py-2">Cadence</th>
                  <th className="px-3 py-2 text-right">Score</th>
                  <th className="px-3 py-2" />
                </tr>
              </thead>
              <tbody>
                {s.rankings.map((r, i) => (
                  <tr key={r.symbol} className={`border-t border-line/60 hover:bg-state-hover/40 ${cfg.market === r.symbol ? 'bg-coral/6' : ''}`}>
                    <td className="num px-3 py-1.5 text-less-prominent">{i + 1}</td>
                    <td className="px-3 py-1.5">
                      <div className="text-prominent">{r.name}</div>
                      <div className="num text-xxs text-less-prominent">{r.symbol}</div>
                    </td>
                    <td className="num px-3 py-1.5 text-right text-general">{r.sample}</td>
                    <td className="px-3 py-1.5 text-right">
                      <span className={`num font-bold ${r.digitEntropy >= 0.97 ? 'text-profit' : r.digitEntropy >= 0.9 ? 'text-orange' : 'text-loss'}`}>
                        {r.digitEntropy.toFixed(4)}
                      </span>
                      <div className="mt-0.5 h-[3px] w-full overflow-hidden rounded bg-line">
                        <div className="h-full rounded bg-accent/70" style={{ width: `${r.digitEntropy * 100}%` }} />
                      </div>
                    </td>
                    <td className="num px-3 py-1.5 text-right text-general">{r.meanAbsMovePips.toFixed(2)}</td>
                    <td className="px-3 py-1.5">
                      <Badge tone={r.cadence === 'fast' ? 'info' : 'neutral'}>{r.cadence}</Badge>
                    </td>
                    <td className="num px-3 py-1.5 text-right font-bold text-coral">{r.score.toFixed(3)}</td>
                    <td className="px-3 py-1.5 text-right">
                      <Button size="sm" variant="ghost" onClick={() => { set({ market: r.symbol }); void s.selectSymbol(r.symbol); }}>
                        Select
                      </Button>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
            <div className="border-t border-line px-3 py-2 text-xxs text-less-prominent">
              {s.rankings.length} markets sampled · {s.rankings.reduce((a, r) => a + r.sample, 0)} ticks collected. Entropy 1.0000 = perfectly
              uniform in this sample.
            </div>
          </div>
        )}
      </Card>

      {cfg.contractType === 'DIGITMATCH' && (
        <Banner tone="warn">
          <Target className="mr-1 inline h-3.5 w-3.5" />
          Digit Matches wins only 1 time in 10. It needs a payout above <strong className="num">10×</strong> stake just to break even before
          fees and slippage. Verify the quoted payout with a live proposal — do not assume a multiple.
        </Banner>
      )}
      {cfg.contractType === 'DIGITDIFF' && (
        <Banner tone="warn">
          Digit Differs wins 9 times in 10, which <em>feels</em> safe and is a classic trap: at a payout below{' '}
          <strong className="num">1.11×</strong> it has negative expected value despite the high win rate. Signal Lab computes this from the
          payout Deriv actually quotes.
        </Banner>
      )}
    </div>
  );
}

